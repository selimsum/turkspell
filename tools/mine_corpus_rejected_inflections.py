_TOKEN_RE = re.compile(r"[a-zA-ZçÇğĞıİöÖşŞüÜâÂîÎûÛ]+")
_VALID_TR_RE = re.compile(r"^[abcçdefgğhıijklmnoöprsştuüvyzâîû]+$")


def tr_lower(s: str) -> str:
    return (
        s.replace("İ", "i")
        .replace("I", "ı")
        .replace("Î", "î")
        .replace("Â", "â")
        .replace("Û", "û")
        .lower()
    )


def hunspell_check_batch(words: list[str], dict_prefix: str) -> set[str]:
    """Returns the subset of `words` REJECTED by Hunspell."""
    rejected = set()
    batch_size = 25000
    for i in range(0, len(words), batch_size):
        batch = words[i : i + batch_size]
        p = subprocess.run(
            [HUNSPELL_BIN, "-d", dict_prefix, "-l"],
            input="\n".join(batch) + "\n",
            text=True,
            capture_output=True,
            encoding="utf-8",
        )
        for line in p.stdout.splitlines():
            w = line.strip()
            if w:
                rejected.add(w)
    return rejected


def load_resources():
    # 1. Active tr.dic entries and their flags
    dic_roots = {}  # lower_head -> list of (head, flags)
    with open(ROOT_DIR / "tr.dic", "r", encoding="utf-8") as f:
        f.readline()
        for line in f:
            line = line.strip()
            if not line:
                continue
            if "/" in line:
                h, fl = line.split("/", 1)
            else:
                h, fl = line, ""
            if h[0].isupper():
                continue
            dic_roots[tr_lower(h)] = (h, fl)

    # 2. TDK & DD lowercase common words
    authority_common = set()
    for fname in ["tdk_words.txt", "dil_dernegi_words.txt"]:
        fpath = ROOT_DIR / "raw_data" / fname
        if fpath.exists():
            with open(fpath, "r", encoding="utf-8", errors="ignore") as f:
                for line in f:
                    w = line.strip().split("/")[0].strip()
                    if w and not w.startswith("#") and " " not in w and not w[0].isupper():
                        authority_common.add(tr_lower(w))

    # 3. English words & proper names to exclude
    english_words = set()
    eng_path = ROOT_DIR / "training" / "english_words_large.txt"
    if eng_path.exists():
        with open(eng_path, "r", encoding="utf-8", errors="ignore") as f:
            for line in f:
                w = line.strip().lower()
                if w:
                    english_words.add(w)

    proper_names = set()
    names_path = ROOT_DIR / "lexicons" / "custom_names.json"
    if names_path.exists():
        with open(names_path, "r", encoding="utf-8") as f:
            for item in json.load(f):
                proper_names.add(tr_lower(item.get("lemma", "")))

    return dic_roots, authority_common, english_words, proper_names


def gather_corpus_tokens() -> Counter:
    counts = Counter()
    cap_counts = Counter()

    # 1. Local Magazine Corpus (15.5 MB)
    mag_path = BENCH_DIR / "data" / "corpora" / "magazine_corpus.txt"
    if mag_path.exists():
        print(f"Scanning {mag_path} ...")
        with open(mag_path, "r", encoding="utf-8", errors="ignore") as f:
            for line in f:
                line = unicodedata.normalize("NFC", line).replace("\u0307", "")
                for t in _TOKEN_RE.findall(line):
                    tl = tr_lower(t)
                    if t[0].isupper():
                        cap_counts[tl] += 1
                    else:
                        counts[tl] += 1

    # 2. Mined 10k OSCAR candidates
    mined_path = ROOT_DIR / "raw_data" / "mined_10k_candidates.json"
    if mined_path.exists():
        print(f"Scanning {mined_path} ...")
        with open(mined_path, "r", encoding="utf-8") as f:
            data = json.load(f)
            if isinstance(data, list):
                for item in data:
                    if isinstance(item, dict):
                        w = tr_lower(item.get("word", ""))
                        c = int(item.get("freq", item.get("count", 5)))
                        if w:
                            counts[w] += c
                    elif isinstance(item, str):
                        counts[tr_lower(item)] += 5
            elif isinstance(data, dict):
                for k, v in data.items():
                    counts[tr_lower(k)] += int(v) if isinstance(v, (int, float)) else 5

    # 3. Turkish Wikipedia & CNN Türk News via polars if available
    try:
        import polars as pl
        wiki_url = "https://huggingface.co/datasets/wikimedia/wikipedia/resolve/main/20231101.tr/train-00000-of-00002.parquet"
        print("Streaming 8,000 Turkish Wikipedia articles...")
        df_wiki = pl.read_parquet(wiki_url, n_rows=8000, columns=["text"])
        for text in df_wiki["text"]:
            if not text:
                continue
            text = unicodedata.normalize("NFC", text).replace("\u0307", "")
            for t in _TOKEN_RE.findall(text):
                tl = tr_lower(t)
                if t[0].isupper():
                    cap_counts[tl] += 1
                else:
                    counts[tl] += 1
    except Exception as e:
        print(f"  Wikipedia stream skipped: {e}")

    # Filter out proper-noun-dominant words and invalid tokens
    filtered = Counter()
    for w, c in counts.items():
        if c < 2 or len(w) < 4 or len(w) > 32:
            continue
        if not _VALID_TR_RE.match(w):
            continue
        if any(w[i] == w[i + 1] == w[i + 2] for i in range(len(w) - 2)):
            continue
        cap_c = cap_counts.get(w, 0)
        if cap_c > 0 and (cap_c / (c + cap_c)) > 0.80:
            continue
        filtered[w] = c

    print(f"Total clean lowercase corpus word types (freq >= 2): {len(filtered):,}")
    return filtered


def get_last_vowel(s: str) -> str:
    for ch in reversed(s):
        if ch in "aeıioöuüâîû":
            return ch
    return ""


def is_harmonic_suffix(stem: str, suffix: str) -> bool:
    """Checks whether the first vowel of `suffix` obeys Turkish vowel harmony with `stem`'s last vowel."""
    lv = get_last_vowel(stem)
    if not lv:
        return False
    first_sv = ""
    for ch in suffix:
        if ch in "aeıioöuü":
            first_sv = ch
            break
    if not first_sv:
        return True
    is_back = lv in "aıouâû"
    if is_back and first_sv not in "aıou":
        return False
    if not is_back and first_sv not in "eiöü":
        return False
    return True


